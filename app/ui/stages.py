"""분석 단계의 사용자 표현 — 무엇을 하고 있는지 말한다 (계획서 §24).

파이프라인의 단계 이름(`jobs/pipeline.py`의 STAGE_*)은 **일감의 이름**이다.
`의미 색인`은 그 일을 만든 사람에게는 정확한 말이지만, 발령 첫날 화면 앞에
앉은 사람에게는 "지금 뭐가 되고 있는 건가"에 답하지 않는다.

두 층으로 나눈다.
    · 상시 화면 — "문서를 읽는 중" 처럼 **지금 무엇이 일어나는지**
    · 상태 상세 대화상자 — 거기서만 기술 이름을 덧붙인다(문제가 났을 때
      무엇을 뒤져야 하는지는 결국 기술 이름으로 물어야 하기 때문이다)

단계 이름 자체를 바꾸지 않는 이유
    그 문자열은 `stage_reports`의 열쇠이고 신호로 오간다. 표시 문구가 바뀔
    때마다 열쇠가 바뀌면 진행 상황이 조용히 두 칸으로 갈라진다. **말은 여기
    한 곳에서만 붙인다** — core/status.py가 상태 어휘를 한 곳에 둔 것과 같다.
"""

from __future__ import annotations

# 단계 이름 → 진행 중일 때 할 말. 계획서 §24가 요구한 "~하는 중" 꼴이다.
RUNNING = {
    "파일 찾기": "파일을 찾는 중",
    "중복 확인": "같은 파일이 있는지 보는 중",
    "내용 읽기": "문서를 읽는 중",
    "시점 확인": "언제 만든 문서인지 보는 중",
    "의미 색인": "비슷한 문서끼리 견줄 수 있게 만드는 중",
    "업무 파악": "업무를 파악하는 중",
    "일정 파악": "반복하는 일을 찾는 중",
    "처리 순서 파악": "처리 순서를 되짚는 중",
    "질문 준비": "질문에 답할 준비를 하는 중",
}

# 끝난 뒤에 할 말. '완료'가 아니라 **무엇을 얻었는지**로 적는다 —
# 사용자가 알고 싶은 것은 단계가 지나갔다는 사실이 아니라 결과다.
DONE = {
    "파일 찾기": "파일을 찾았습니다",
    "중복 확인": "같은 파일을 가려냈습니다",
    "내용 읽기": "문서를 읽었습니다",
    "시점 확인": "문서의 시점을 확인했습니다",
    "의미 색인": "문서끼리 견줄 준비를 마쳤습니다",
    "업무 파악": "업무를 나눴습니다",
    "일정 파악": "반복하는 일을 찾았습니다",
    "처리 순서 파악": "처리 순서를 되짚었습니다",
    "질문 준비": "질문에 답할 준비를 마쳤습니다",
}

# 상태 상세에서만 덧붙이는 기술 이름. 여기 없는 단계는 덧붙일 것이 없다.
TECHNICAL = {
    "파일 찾기": "scan",
    "중복 확인": "SHA-256",
    "내용 읽기": "parse",
    "시점 확인": "date inference",
    "의미 색인": "embedding · bge-m3",
    "업무 파악": "clustering",
    "일정 파악": "cycle inference",
    "처리 순서 파악": "step reconstruction",
    "질문 준비": "chunking + embedding",
}


def running(stage: str) -> str:
    return RUNNING.get(stage, stage)


def done(stage: str) -> str:
    return DONE.get(stage, stage)


def technical(stage: str) -> str:
    """'의미 색인 (embedding · bge-m3)'. 붙일 것이 없으면 이름 그대로."""
    hint = TECHNICAL.get(stage)
    return f"{stage} ({hint})" if hint else stage
